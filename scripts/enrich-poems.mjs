/* ---------------- 体裁判定 ---------------- */
function lineChars(line) {
  // 去掉标点，返回汉字数
  return line.text.replace(/[^\u4e00-\u9fa5]/g, '').length;
}
function classifyGenre(poem) {
  const lines = poem.lines;
  const n = lines.length;
  const counts = lines.map(lineChars);
  const allEqual = counts.every((c) => c === counts[0]);
  const c0 = counts[0];
  // 近体诗：句数 4 或 8，字数整齐
  if (allEqual) {
    if (n === 4 && c0 === 5) return '五言绝句';
    if (n === 4 && c0 === 7) return '七言绝句';
    if (n === 8 && c0 === 5) return '五言律诗';
    if (n === 8 && c0 === 7) return '七言律诗';
    if (n === 6 && c0 === 5) return '五言古诗';
    if (n === 6 && c0 === 7) return '七言古诗';
    if (n === 4) return '古体诗';
    if (n === 8) return '古体诗';
    return '古体诗';
  }
  // 长短句（字数不齐）→ 词 / 曲 / 乐府
  const dyn = poem.dynasty;
  if (dyn === '宋' || dyn === '五代') return '词';
  if (dyn === '元') return '曲';
  if (dyn === '唐') return '乐府';
  if (dyn === '先秦' || dyn === '汉') return '诗经楚辞';
  return '古体诗';
}

function difficultyOf(poem, genre) {
  // 依据体裁与现有 level 估算研读难度（1-5）
  const base = { '五言绝句': 1, '七言绝句': 2, '五言古诗': 2, '七言古诗': 3, '五言律诗': 4, '七言律诗': 5, '词': 3, '曲': 3, '乐府': 2, '古体诗': 2, '诗经楚辞': 3 }[genre] ?? 2;
  return Math.min(5, Math.max(1, base));
}

function buildImagery(poem) {
  const text = poem.lines.map((l) => l.text).join('');
  const found = IMAGERY_KEYWORDS.filter((k) => text.includes(k));
  // 去重并保持顺序
  return [...new Set(found)];
}

const out = poems.map((p) => {
  const genre = classifyGenre(p);
  const themes = [...new Set(p.tags || [])];
  const imagery = buildImagery(p);
  const authorBio = AUTHOR_BIOS[p.author] || `${p.author}（${p.dynasty}诗人，作者简介整理中）`;
  return {
    ...p,
    genre,
    themes,
    imagery,
    authorBio,
    difficulty: difficultyOf(p, genre),
  };
});

