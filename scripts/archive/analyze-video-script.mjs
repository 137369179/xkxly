function buildVoiceText(char) {
  const info = LIUSHU_STORIES[char];
  if (!info) return null;
  
  return `小朋友们好！欢迎来到《宝贝学习乐园》！今天我们学习汉字「${char}」。\n\n` +
         `这个字是个${info.type}字。\n` +
         `${info.desc ? '它的意思是：' + info.desc + '。\n\n' : ''}` +
         `${info.story}\n\n` +
         `记住口诀：「${info.rhyme}」。\n\n` +
         `组词练习：${info.words.join('、')}。\n` +
         `跟读：${info.words.join('，')}, ${info.words.join('，')}。\n\n` +
         `造句：${info.sentence}。\n\n` +
         `复习：「${char}」是${info.type}，${info.memoryTip}。\n` +
         `太棒了！你已经学会「${char}」这个字了！给自己鼓鼓掌吧！`;
}

function main() {
  console.log('=== 汉字教学视频脚本示例 ===\n');
  
  // 选择几个代表性汉字展示
  const sampleChars = ['日', '月', '山', '水', '火', '人', '一', '二', '三', '明', '春', '秋', '休', '森', '妈', '爸'];
  
  for (const char of sampleChars) {
    const text = buildVoiceText(char);
    if (text) {
      console.log(`【${char}】`);
      console.log(`类型: ${LIUSHU_STORIES[char].type}`);
      console.log(`描述: ${LIUSHU_STORIES[char].desc}`);
      console.log(`故事: ${LIUSHU_STORIES[char].story.substring(0, 50)}...`);
      console.log(`口诀: ${LIUSHU_STORIES[char].rhyme.substring(0, 40)}...`);
      console.log(`时长: ${Math.ceil(text.length / 4)}秒`);
      console.log('');
    }
  }
  
  console.log('\n完整语音文本示例（以"日"为例）:');
  console.log(buildVoiceText('日'));
}

main();
