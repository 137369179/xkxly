/** 判断文本是否恰好是单个已收录汉字（去除空白与常见标点后） */
export function isSingleHanziVoice(text: string): boolean {
  const s = text.trim();
  return s.length === 1 && HANZI_VOICE_CHARS.has(s);
}

/** 取某个字的本地 mp3 相对 URL（不含 BASE_URL，由调用方决定是否拼前缀） */
export function hanziVoiceUrl(char: string): string {
  return `/hanzi-voices/${char}.mp3`;
}

/** 模块级复用的 Audio 元素（同一时刻只播一个字，天然互斥） */
let sharedAudio: HTMLAudioElement | null = null;

/**
 * 播放单个汉字的本地发音。
 * 返回 Promise：正常播完 resolve；资源加载失败 / 环境无 Audio 则 reject，
 * 让调用方（speak）回退到原 TTS 链路。
 */
export function playHanziVoice(char: string, onEnd?: () => void): Promise<void> {
  return new Promise((resolve, reject) => {
    if (typeof window === 'undefined' || !('Audio' in window)) {
      reject(new Error('no-audio'));
      return;
    }
    const url = hanziVoiceUrl(char);
    // 复用实例：换 src 后 load()，避免每次 new Audio 累积内存
    if (!sharedAudio) {
      sharedAudio = new Audio();
      sharedAudio.preload = 'auto';
    }
    const audio = sharedAudio;
    const done = () => {
      audio.onended = null;
      audio.onerror = null;
      onEnd?.();
      resolve();
    };
    const fail = () => {
      audio.onended = null;
      audio.onerror = null;
      reject(new Error('voice-load-failed'));
    };
    audio.onended = done;
    audio.onerror = fail;
    audio.src = url;
    audio.play().catch(fail);
  });
}
