/**
 * 判断一段输入文本是否为拼音，并将其转换为标准发音文字
 */
export function pinyinToSpoken(raw: string): string {
  const t = raw.trim().toLowerCase();
  if (!t) return raw;

  // 1. 是否为单声母 (b, p, m, f...)
  if (SHENGMU_MAP[t]) return SHENGMU_MAP[t]!;

  // 2. 是否为单韵母或复韵母 (a, o, e, ai, ei...)
  if (YUNMU_MAP[t]) return YUNMU_MAP[t]!;

  // 3. 是否为速查音节库中的带调音节 (bā, bǐ, huā, zhī...)
  if (PINYIN_SYLLABLE_MAP[t]) return PINYIN_SYLLABLE_MAP[t]!;

  return raw;
}
