/** 查某字平水韵归属；未收录返回 undefined（引擎降级用现代十三辙） */
export function yunBuOf(c: string): PingShuiEntry | undefined {
  return PING_SHUI[c];
}

/** 取平声韵部简称（如「七阳」），非平声返回空串 */
export function yunBuShort(c: string): string {
  const e = PING_SHUI[c]!
  if (!e || e.tone !== '平') return '';
  return e.bu.replace(/^(上平|下平)/, '');
}
