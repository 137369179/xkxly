/** 核心数字 0-9 的趣闻；数字 n>9 时走 fallback（用 n 的奇偶性补充说明） */
const DIGIT_FACTS: Record<number, string> = {
  0: '0 站在别的数字后面，能把这个数变得更大！比如 10、100、1000。',
  1: '1 表示"一个"，是所有数里最基础、最著名的起点。',
  2: '2 表示一对。我们常说的"成双成对"，好朋友就是两个人。',
  3: '3 代表"很多"，三三两两、三五成群，讲的就是三个或更多。',
  4: '4 能组成正方形——四条一样长的边，稳稳当当。',
  5: '5 就是我们一只手的手指数量，数一数：一、二、三、四、五！',
  6: '6 像一把小勺子。六边形也有六条边，像蜂窝一样。',
  7: '7 是一周的天数：星期一到星期日，一共七天。',
  8: '8 躺下来就是无穷大符号 ∞，表示"永远"那么多了不起！',
  9: '9 是一位数里最大的，再往前一步就是两位数的 10 啦。',
};

const FALLBACK_FACT = '这个数比 9 还大，代表更多数量；勤练习能数得又快又准！';

/** 返回数字 n 的趣味小知识；n 不在 0-9 时返回兜底文案 */
export function numberFact(n: number): string {
  return DIGIT_FACTS[n] ?? FALLBACK_FACT;
}

/** 已覆盖的核心数字（用于数据完整性校验） */
export const FACT_NUMBERS: readonly number[] = Object.keys(DIGIT_FACTS).map(Number);