/**
 * 数字王国 · 按数字的离线小童谣（静态兜底内容）
 * ------------------------------------------------------------------
 * 用于 AI 数字儿歌在弱网/AI 不可用时的兜底：即时展示、无网络依赖。
 * 与 numberFacts(趣味小知识) 相互独立，避免在弹窗中重复显示同一内容。
 */

const RHYMES: Record<number, string> = {
  0: '零呀零，像甜甜圈，圆圆的圈圈站中间。',
  1: '一呀一，像根小蜡笔，一步一步来学习。',
  2: '二呀二，像只小鸭子，摇摇摆摆真神气。',
  3: '三呀三，像只小耳朵，认真听话不会错。',
  4: '四呀四，像面小旗子，四个方向我记牢。',
  5: '五呀五，像把小钩子，一只手儿有五指。',
  6: '六呀六，像个小口哨，吹出欢快的歌谣。',
  7: '七呀七，像把小锄头，一周七天乐悠悠。',
  8: '八呀八，像个小葫芦，摇呀摇呀数一数。',
  9: '九呀九，像只小气球，飘呀飘呀飞天空。',
};

const FALLBACK_RHYME = '数呀数，越来越大，一步一步不害怕。';

/** 返回数字 n 的离线童谣；n 不在 0-9 时返回兜底童谣 */
export function numberRhyme(n: number): string {
  return RHYMES[n] ?? FALLBACK_RHYME;
}

/** 已覆盖的核心数字（供数据完整性校验） */
export const RHYME_NUMBERS: readonly number[] = Object.keys(RHYMES).map(Number);