/**
 * 贴纸收集册
 *
 * 产品依据：帮帮识字「积分兑换虚拟勋章 / 互动宠物」、洪恩「奇趣动物园」。
 * 徽章是"被动达成"，贴纸是"主动选择花星星换"——两者动机不同：
 * 前者给成就感，后者给**收集欲与掌控感**，是拉动孩子第二天回来的关键。
 */

const A = (
  album: string,
  tone: Tone,
  cost: number,
  items: [string, string][],
): StickerDef[] =>
  items.map(([emoji, name], i) => ({
    id: `${album}-${i}`,
    emoji,
    name,
    album,
    cost,
    tone,
  }));

