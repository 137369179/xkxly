/** 获取关卡数据（带默认容错） */
export function getKingdomLevel(pinyinSymbol: string): KingdomPinyinLevel {
  const clean = pinyinSymbol.trim().toLowerCase();
  const found = KINGDOM_LEVELS.find((l) => l.p === clean || l.id === clean);
  if (found) return found;

  // 兜底动态生成符合规格的对象
  return {
    id: clean,
    p: clean,
    name: `拼音 ${clean}`,
    type: 'yunmu',
    category: 'compound',
    islandId: 'compound_nasal',
    order: 99,
    levelNumber: 99,
    rhyme: `标准拼音 ${clean}，发音清晰又好听`,
    mouthGuide: '观察口型，注意气流平稳自然发出！',
    personification: {
      character: '拼音精灵',
      emoji: '✨',
      badge: '拼音星徽',
      visualDesc: `闪烁着七彩光芒的拼音精灵「${clean}」`,
      interactivePrompt: '戳戳神奇的拼音精灵，听听它的发音！',
      interactiveFeedback: `拼音精灵欢快地唱出了「${clean}」！`,
      funFact: `拼音 ${clean} 是汉语拼音大家庭中的闪亮成员！`,
    },
    fourLineGrid: {
      position: 'middle',
      gridDesc: '住在四线三格的「中格」，工整书写不越线',
      strokeCount: clean.length,
      strokeNames: clean.split('').map((c, i) => `第 ${i + 1} 字母 ${c}`),
      strokeGuides: clean.split('').map((c) => `按规范书写字母 ${c}`),
    },
    examples: [],
    badgeReward: { id: `badge_${clean}`, title: `${clean} 探索星`, icon: '🌟' },
  };
}
