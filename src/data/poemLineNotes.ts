import type { PoemLineNote } from '@/types';

/**
 * 逐句权威串讲库
 * ---------------------------------------------------------------
 * 每首诗的注释数组下标严格与 `poem.lines` 对齐（第 i 条对应第 i 句）。
 * 单条结构：
 *   gloss  句意直译（必填）
 *   keys   字词训释（可选，term=词条 / note=训释）
 *   point  赏析要点（可选，只在关键句给出，避免每句都评破坏节奏）
 *
 * 扩展方式：新增诗只需在 POEM_LINE_NOTES 中追加一个 id 键，
 * 行数与 poems-deep.json 中该诗 lines 长度一致即可，界面自动生效。
 */

type KV = [term: string, note: string];

function ln(gloss: string, keys?: KV[], point?: string): PoemLineNote {
  return {
    gloss,
    ...(keys && keys.length ? { keys: keys.map(([term, note]) => ({ term, note })) } : {}),
    ...(point ? { point } : {}),
  };
}

