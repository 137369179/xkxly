/**
 * 诗人史料档案库
 * ---------------------------------------------------------------
 * 每位诗人一条 PoetProfile：
 *   life      生卒年（不可考者标「生卒年不详」）
 *   style     字、号
 *   epithet   世称 / 谥号 / 雅号
 *   bio       生平概述
 *   timeline  编年大事（年份 + 事件），用于时间轴可视化
 *   art       艺术成就与诗风
 *   works     代表作
 *   sources   史料出处（正史列传、墓志、年谱、别集序跋等）
 *
 * 扩展方式：按 `name` 为键追加即可，界面通过 poem.author 自动关联。
 */

type TL = [year: string, event: string];
type SRC = [title: string, note?: string];

function t(items: TL[]) {
  return items.map(([year, event]) => ({ year, event }));
}
function s(items: SRC[]) {
  return items.map(([title, note]) => (note ? { title, note } : { title }));
}

