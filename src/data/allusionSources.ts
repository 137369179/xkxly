/** 维基文库全文检索链接（用于跳转查证原始史料） */
export function sourceSearchLink(source: string): string {
  // 取书名号中的主书名，如「《后汉书·窦融列传附窦宪传》」-> 后汉书
  const m = source.match(/《([^·》]+)/);
  const q = m ? m[1] : source;
  return EXTERNAL_LINKS.wikisource(q!);
}

/** 按典故词条取溯源资料 */
export function lookupAllusion(term: string): AllusionSource | undefined {
  return ALLUSION_SOURCES[term];
}
